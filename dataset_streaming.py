"""

Pipeline: stream -> normalize -> dedup -> AST validity+structure
          -> token count -> bucket -> repo cap -> reservoir sample
          -> shuffle -> token budget truncation -> save
"""

import ast
import hashlib
import random
import re
from collections import defaultdict
from datasets import load_dataset, Dataset
from transformers import AutoTokenizer
from tqdm import tqdm


TOKENIZER_PATH = "./TeacherModel/Qwen2.5-Coder/"

SEED = 42
random.seed(SEED)

BUCKETS = {
    "short":  (128,   1024),
    "medium": (1024,  4096),
    "long":   (4096,  8192),
}

BUCKET_TOKEN_TARGETS = {
    "short":  20_000_000,
    "medium": 40_000_000,
    "long":   40_000_000,
}

MAX_PER_REPO = {
    "short":  15,
    "medium": 25,
    "long":   40,
}

GEOMETRIC_MEAN_TOKENS = {
    "short":  565,
    "medium": 2048,
    "long":   5793,
}
RESERVOIR_OVERSAMPLE = 2.0

OUTPUT_PATH = "./Code_parrot_dataset"


MAX_SCAN = 1200000

def is_python_file(example) -> bool:
    path = example.get("path", "")
    return path.endswith(".py")

def normalize_blank_lines(code: str) -> str:
    return re.sub(r"\n{3,}", "\n\n", code.strip())


def hash_code(code: str) -> str:
    return hashlib.md5(code.encode("utf-8")).hexdigest()


def parse_and_check(code: str):
    
    try:
        tree = ast.parse(code)
    except (SyntaxError, ValueError, RecursionError):
        return False, False
    has_structure = any(
        isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        for node in ast.walk(tree)
    )
    return True, has_structure


def get_bucket(num_tokens: int):
    for name, (lo, hi) in BUCKETS.items():
        if lo <= num_tokens < hi:
            return name
    return None


def reservoir_add(reservoir: list, item, capacity: int, count_seen: int):
    if len(reservoir) < capacity:
        reservoir.append(item)
    else:
        j = random.randint(0, count_seen - 1)
        if j < capacity:
            reservoir[j] = item


def sample_dataset():
    print("Loading tokenizer...")
    tokenizer = AutoTokenizer.from_pretrained(TOKENIZER_PATH)

    print("Opening stream — codeparrot-clean")
    stream = load_dataset(
        "codeparrot/codeparrot-clean",
        streaming=True,
        split="train",
        trust_remote_code = True
    )

    reservoir_capacity = {
        b: int((BUCKET_TOKEN_TARGETS[b] / GEOMETRIC_MEAN_TOKENS[b]) * RESERVOIR_OVERSAMPLE)
        for b in BUCKETS
    }
    print(f"Reservoir capacities: {reservoir_capacity}")
    print(f"Will scan up to {MAX_SCAN:,} examples (full scan, no early stop)")

    seen_hashes = set()
    repo_counts_by_bucket = defaultdict(lambda: defaultdict(int))
    reservoirs = {b: [] for b in BUCKETS}
    bucket_seen_count = defaultdict(int)

    total_scanned = 0
    skipped = {
       "wrong_language": 0, "duplicate": 0, "invalid_ast": 0, "no_structure": 0,
        "repo_cap": 0, "no_bucket": 0, "empty": 0, "autogenerated": 0
    }

    pbar = tqdm(stream, desc="Streaming + filtering", total=MAX_SCAN)

    for example in pbar:
        total_scanned += 1
        if total_scanned > MAX_SCAN:
            print("\nReached MAX_SCAN — stopping (full-scan policy honored).")
            break

        if not is_python_file(example):
            skipped["wrong_language"]+=1
            continue

        if example.get("autogenerated", False):
            skipped["autogenerated"]+=1
            continue

        raw_code = example.get("content", "")
        if not raw_code or not raw_code.strip():
            skipped["empty"] += 1
            continue

        
        code = normalize_blank_lines(raw_code)

        
        h = hash_code(code)
        if h in seen_hashes:
            skipped["duplicate"] += 1
            continue
        seen_hashes.add(h)

        
        is_valid, has_structure = parse_and_check(code)
        if not is_valid:
            skipped["invalid_ast"] += 1
            continue
        if not has_structure:
            skipped["no_structure"] += 1
            continue

        char_len = len(code)
        if char_len < 400 or char_len > 40_000:
            skipped["no_bucket"] += 1
            continue

        
        num_tokens = len(tokenizer(code, truncation=False)["input_ids"])
        bucket = get_bucket(num_tokens)
        if bucket is None:
            skipped["no_bucket"] += 1
            continue

        
        repo = example.get("repo_name", "unknown")
        if repo_counts_by_bucket[bucket][repo] >= MAX_PER_REPO[bucket]:
            skipped["repo_cap"] += 1
            continue
        repo_counts_by_bucket[bucket][repo] += 1

        
        bucket_seen_count[bucket] += 1
        item = {
            "code": code,
            "repo_name": repo,
            "bucket": bucket,
            "num_tokens": num_tokens,
        }
        reservoir_add(
            reservoirs[bucket], item,
            reservoir_capacity[bucket], bucket_seen_count[bucket]
        )

        pbar.set_postfix({
            b: f"{len(reservoirs[b])}/{reservoir_capacity[b]}"
            for b in BUCKETS
        })

        

    print(f"\nScanned {total_scanned:,} examples")
    print(f"Skipped — wrong_language: {skipped['wrong_language']:,}, "
          f"autogenerated: {skipped['autogenerated']:,},"
          f"duplicate: {skipped['duplicate']:,}, "
          f"invalid_ast: {skipped['invalid_ast']:,}, "
          f"no_structure: {skipped['no_structure']:,}, "
          f"repo_cap: {skipped['repo_cap']:,}, "
          f"no_bucket: {skipped['no_bucket']:,}, "
          f"empty: {skipped['empty']:,}")

    
    final_samples = []
    for b, reservoir in reservoirs.items():
        random.shuffle(reservoir)
        token_budget = BUCKET_TOKEN_TARGETS[b]
        running_total = 0
        kept = []
        for item in reservoir:
            if running_total + item["num_tokens"] > token_budget:
                continue
            kept.append(item)
            running_total += item["num_tokens"]
            if running_total >= token_budget * 0.98:
                break
        print(f"  bucket {b:>8}: {len(kept):,} samples, "
              f"{running_total/1e6:.2f}M tokens (target {token_budget/1e6:.0f}M)")
        final_samples.extend(kept)

    random.shuffle(final_samples) 
    total_tokens = sum(s["num_tokens"] for s in final_samples)
    print(f"\nFinal dataset: {len(final_samples):,} samples, "
          f"{total_tokens/1e6:.2f}M tokens total")

    dataset = Dataset.from_list(final_samples)
    dataset.save_to_disk(OUTPUT_PATH)
    print(f"Saved to {OUTPUT_PATH}")
    return dataset


if __name__ == "__main__":
    ds = sample_dataset()
    print("\nSample 0:")
    print(f"  repo:   {ds[0]['repo_name']}")
    print(f"  bucket: {ds[0]['bucket']}")
    print(f"  tokens: {ds[0]['num_tokens']}")
  